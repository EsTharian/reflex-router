#!/usr/bin/env node
// Generates src/wire/tested-versions.generated.ts from the directory names under test/fixtures/claude-code/.
// The npm package does not ship test/, so the runtime needs the list as code. `--check` fails on drift.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";

const FIXTURES = "test/fixtures/claude-code";
const OUT = "src/wire/tested-versions.generated.ts";

const cmp = (a, b) => {
  const pa = a.split(".").map(Number), pb = b.split(".").map(Number);
  return pa[0] - pb[0] || pa[1] - pb[1] || pa[2] - pb[2];
};
const versions = existsSync(FIXTURES) ? readdirSync(FIXTURES).filter((d) => /^\d+\.\d+\.\d+$/.test(d)).sort(cmp) : [];
const content = `// GENERATED by scripts/gen-tested-versions.mjs from ${FIXTURES}/. Do not edit; run \`npm run gen:versions\`.
// Claude Code versions we hold captured, redacted fixtures for.
export const TESTED_CLAUDE_VERSIONS: readonly string[] = ${JSON.stringify(versions)};
`;

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (current !== content) {
    console.error(`${OUT} is out of date with ${FIXTURES}/; run \`npm run gen:versions\``);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${versions.join(", ") || "no versions"})`);
} else {
  writeFileSync(OUT, content);
  console.log(`wrote ${OUT}: ${versions.join(", ") || "no versions"}`);
}
